public class Lesson0 {//메인 클래스
    public static void main(String[] args) { //메인 함수 (프로그램 시작점)
        // command + 1 : 프로젝트 창 열고 닫기
        // ctrl + / : 주석단축기
        // ctrl + shift + / : 여러줄 주석
        // command + option + L : 코드 자동 정렬
        // control + R = 코드 실행
        // control + shift + R = 커서 있는 코드 실행
        System.out.println("안녕하세요 자바!");

        // System : 시스템
        // out : 밖에서
        // print : 출력
        // ln(line) : 한줄마다 출력력
        // sout + tap : System.out.println() 완성
        System.out.print("반가워\n");
        System.out.print("잘잤니\n");
    }
}
